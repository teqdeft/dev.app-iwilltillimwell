                        <ol>
                            <li>Call <a href="tel:988">988</a> and press 1</li>
                            <li>Text <a href="sms:838255">838255</a> - connects you to the Veterans Crisis Line by text. (A trained VA crisis responder will text you back, ask a few brief questions about what’s going on and your safety, and then stay with you in the conversation, helping you cope in the moment and, if you want, connecting you with follow up support. You can share as much or as little as you choose, and you can end the text conversation at any time by texting something like “STOP.”)</li>
                            <li>Chat at veteranscrisisline.net</li>
                        </ol>
                    </li>

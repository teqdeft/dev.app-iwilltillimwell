            </div>
            <div class="text">
                <ul>
                    <li>Call <a href="tell:711">911</a> for any immediate danger or life threatening emergency, 24/7.</li>
                    <li>Call <a href="tell:711">988</a> Suicide & Crisis Lifeline (formerly National Suicide Prevention Lifeline) - appropriate for all ages, any crisis for urgent mental health or suicidal crisis support, 24/7
                        <ol>
                            <li>TTY users can dial <a href="tell:711">711</a> then <a href="tell:988">988</a> for the Suicide & Crisis Lifeline.</li>
                            <li>Call: <a href="tel:1800273">1 800 273</a>  TALK (8255) which still connects into 988</li>
                            <li>Text: <a href="sms:988?body=AYUDA">988</a> (or text “AYUDA” to 988 for Spanish or select Spanish on the Lifeline website)</li>
                            <li>Chat: Via the “Chat” button at <a href="https://988lifeline.org/">988lifeline.org</a>.</li>
                        </ol>
                    </li>
                </ul>

                <p class="people-v1">These resources are for people of all ages, backgrounds, identities, and immigration statuses. You do
                    not need to be in active suicidal crisis to reach out.</p>

                <p class="people-v1">TTY users can dial <a href="tell:711">711</a>, then <a href="tell:988">988</a>. Many hotlines offer interpreters and services in multiple languages. Ask the counselor for help or check each website.</p>
